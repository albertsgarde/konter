//! Writing hledger journals: everything in ledger/ is written here.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use jiff::civil::Date;

use crate::model::LedgerTransaction;
use crate::money::fmt_amount;

pub const HEADER_PREFIX: &str = "; Generated by konter";

/// The first line of every generated journal; `verify` reads `--as-of` back from it.
pub fn header_line(as_of: Date) -> String {
    format!("{HEADER_PREFIX} with --as-of {as_of}. Do not edit.")
}

/// Reads `--as-of` back from a generated journal's first line.
pub fn as_of_from_header(text: &str) -> Option<Date> {
    let first = text.lines().next()?;
    let rest = first.strip_prefix(HEADER_PREFIX)?;
    rest.split("--as-of ").nth(1)?.get(..10)?.parse().ok()
}

/// hledger ends descriptions at `;` and can't have newlines in them.
fn clean(text: &str) -> String {
    text.replace(['\n', '\r'], " ").replace(';', ",")
}

pub fn render_transaction(out: &mut String, tx: &LedgerTransaction) {
    let tags: Vec<String> = tx.tags.iter().map(|(k, v)| format!("{k}:{v}")).collect();
    let _ = write!(out, "{} {}", tx.date, clean(&tx.description));
    if !tags.is_empty() {
        let _ = write!(out, "  ; {}", tags.join(", "));
    }
    out.push('\n');
    for c in &tx.comments {
        let _ = writeln!(out, "    ; {}", clean(c));
    }
    let width = tx.postings.iter().map(|p| p.account.chars().count()).max().unwrap_or(0).max(36);
    for p in &tx.postings {
        let amount = fmt_amount(p.amount, &p.commodity);
        let pad = width - p.account.chars().count();
        let _ = write!(out, "    {}{}  {:>16}", p.account, " ".repeat(pad), amount);
        if let Some((cost, commodity)) = &p.total_cost {
            let _ = write!(out, " @@ {}", fmt_amount(*cost, commodity));
        }
        if let Some(b) = p.assert_balance {
            let _ = write!(out, " = {}", fmt_amount(b, &p.commodity));
        }
        if let Some(c) = &p.comment {
            let _ = write!(out, "  ; {}", clean(c));
        }
        out.push('\n');
    }
}

/// The order transactions are written in: by date, and within a date by
/// provenance, so balance assertions hold in booking order.
pub fn ordered(txs: &[LedgerTransaction]) -> Vec<&LedgerTransaction> {
    let mut out: Vec<&LedgerTransaction> = txs.iter().collect();
    out.sort_by(|a, b| (a.date, &a.provenance).cmp(&(b.date, &b.provenance)));
    out
}

/// ledger/main.journal, hledger's entry point.
pub const MAIN: &str = "\
; Generated by konter. Do not edit: everything in ledger/ is written by konter.
; Entry point for hledger: `hledger -f ledger/main.journal ...` (or `just more hl ...`).
include generated.journal
include forecast.journal
";

/// Renders ledger/generated.journal: header, the books' currency and every
/// account, then transactions sorted by date (and, within a date, in
/// generation order per provenance).
pub fn render(as_of: Date, currency: &str, accounts: &BTreeSet<String>, txs: &[LedgerTransaction]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "{}", header_line(as_of));
    let _ = writeln!(
        out,
        "; Bank transactions mapped by config/rules/, subscriptions, and the transactions\n\
         ; in config/transactions.toml. Accounts from config/accounts.toml and konter's own.\n"
    );
    let _ = writeln!(out, "commodity 1000.00 {currency}\n");
    for a in accounts {
        let _ = writeln!(out, "account {a}");
    }
    for tx in ordered(txs) {
        out.push('\n');
        render_transaction(&mut out, tx);
    }
    out
}
